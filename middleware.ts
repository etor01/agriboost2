// middleware.ts

import { NextResponse, type NextRequest } from 'next/server'
import { updateSession } from '@/lib/supabase/middleware'

export async function middleware(request: NextRequest) {
  // This function is imported from the helper file.
  // Its only job is to run the logic from the helper.
  return await updateSession(request)
}

export const config = {
  matcher: [
    /*
     * Match all request paths except for the ones starting with:
     * - _next/static (static files)
     * - _next/image (image optimization files)
     * - favicon.ico (favicon file)
     * - api (API routes)
     * PWA-specific exclusions (must be publicly accessible with no auth redirect):
     * - manifest.json (Web App Manifest)
     * - sw.js / workbox-*.js (Service Worker files — generated by next-pwa)
     * - custom-sw.js (our push + sync extension)
     * - icons/ (PWA icon set)
     * - screenshots/ (manifest screenshots)
     * - robots.txt (search indexing)
     */
    '/((?!_next/static|_next/image|favicon.ico|api/|manifest\\.json|sw\\.js|workbox-.*|worker-.*|icons/|screenshots/|robots\\.txt).*)',
  ],
}
